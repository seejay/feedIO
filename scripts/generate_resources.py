"""Regenerate embedded Qt resources using Qt 6's rcc (no PySide dependency)."""
import argparse
from pathlib import Path
import re
import shutil
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument('--rcc', help='Path to the Qt 6 rcc executable')
args = parser.parse_args()
compiler = args.rcc or shutil.which('rcc')
if not compiler and Path('/usr/lib/qt6/rcc').is_file():
    compiler = '/usr/lib/qt6/rcc'
if not compiler:
    parser.error('Install Qt 6 development tools and pass --rcc /path/to/rcc')
root = Path(__file__).resolve().parents[1]
source = root / 'feedio/UI/feedIOicons.qrc'
# Format 1 omits file timestamps; uncompressed bytes avoid codec-version drift.
result = subprocess.run([compiler, '-g', 'python', '--format-version', '1', '--no-compress', str(source)],
                        check=True, capture_output=True, text=True)
code = result.stdout.replace('from PySide6 import QtCore', 'from PyQt6 import QtCore')
code = re.sub(r'# Created by: The Resource Compiler for Qt version .*',
              '# Generated by scripts/generate_resources.py using Qt 6 rcc', code)
source.with_name('feedIOicons_rc.py').write_text(code, encoding='utf-8')
